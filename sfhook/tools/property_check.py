#!/usr/bin/env python3
"""Compile the actual Android float parser on the host and exercise profile-3 shader gains."""
from pathlib import Path
import re
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
source = (root / "oulg_sf.c").read_text()
parser = re.search(r"static float prop_float\(.*?\n\}", source, re.S).group(0)
assert 'p[3].light = prop_float("debug.oulg.sf.qslight", OULG_QS_LIGHT_DEFAULT);' in source
with tempfile.TemporaryDirectory() as tmp:
    temp = Path(tmp)
    harness = r'''
#include <assert.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define PROP_VALUE_MAX 92
static const char *value;
static int __system_property_get(const char *key,char *out) {
    (void)key;
    if(!value)return 0;
    strcpy(out,value);return (int)strlen(value);
}
'''
    harness += parser + r'''
int main(void) {
    const char *valid[]={"0","0.90","2"};
    const float expect[]={0,.90f,2};
    for(int i=0;i<3;i++){value=valid[i];assert(fabsf(prop_float("qslight",.90f)-expect[i])<.0001f);}
    const char *bad[]={NULL,"","NaN","Infinity","-Infinity","1oops","1e999"};
    for(int i=0;i<7;i++){value=bad[i];assert(prop_float("qslight",.90f)==.90f);}
    puts("property parser: finite/default/trailing-input checks passed");
}
'''
    (temp / "parser.c").write_text(harness)
    subprocess.run(["cc", "-std=c99", "-Wall", "-Wextra", "-Werror", str(temp / "parser.c"), "-lm", "-o", str(temp / "parser")], check=True)
    subprocess.run([str(temp / "parser")], check=True)
    exe = temp / "refract"
    subprocess.run(["cc", "-std=c99", "-I"+str(root), str(root / "tools/refract_check.c"), "-o", str(exe)], check=True)
    text = {}
    for gain in ("0", "0.90", "2", "NaN", "3"):
        out = temp / gain
        out.mkdir()
        subprocess.run([str(exe), str(root / "tools/testdata/synthetic_dump.txt"), str(out), "0", "qslight="+gain], check=True, stdout=subprocess.DEVNULL)
        text[gain] = (out / "mod_002.frag").read_text()
    assert text["NaN"] == text["0"] == text["3"], "invalid gain must use the native default"
    assert text["0"] != text["0.90"] != text["2"]
    # All generated bytes outside the profile-3 edge function stay identical.
    strip = lambda s: re.sub(r"oulg_glow\(s, uv, (?:0\.000|0\.900|2\.000), 18\.000,", "QS_GAIN", s)
    assert strip(text["0"]) == strip(text["0.90"]) == strip(text["2"])
    print("profile 3: gain 0/default/2, invalid fallback and other-profile isolation passed")
