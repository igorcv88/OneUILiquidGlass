#!/usr/bin/env python3
"""Generate localized descriptions for reviewed settings."""
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'tools/control-descriptions.json').read_text())
source = (root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/config/Controls.java').read_text()
known = set(re.findall(r'put\(c\("([^"]+)"', source))
if set(data) - known:
    raise SystemExit(f'Unknown controls: {sorted(set(data) - known)}')
for folder, index in [('values', 0), ('values-pt-rBR', 1)]:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for key, values in sorted(data.items()):
        name = 'control_description_' + key.replace('.', '_')
        value = escape(values[index]).replace("'", "\\'")
        lines.append(f'    <string name="{name}">{value}</string>')
    lines.append('</resources>')
    (root / f'app/src/main/res/{folder}/control_descriptions.xml').write_text('\n'.join(lines) + '\n')
lines = ['package io.github.igorcv88.oneuiliquidglass.ui;', '', 'import android.content.Context;', 'import io.github.igorcv88.oneuiliquidglass.R;', 'import io.github.igorcv88.oneuiliquidglass.config.Controls;', '', '/** Generated by tools/generate-control-descriptions.py. */', 'final class ControlDescriptions {', '    static int resource(String key) {', '        switch (key) {']
for key in sorted(data):
    lines.append(f'            case {json.dumps(key)}: return R.string.control_description_{key.replace(".", "_")};')
lines += ['            default: return 0;', '        }', '    }', '    static String hint(Context c, Controls.Control control) {', '        int id = resource(control.key);', '        return id == 0 ? control.hint : c.getString(id);', '    }', '    static String help(Context c, Controls.Control control) {', '        int id = resource(control.key);', '        return id == 0 ? control.help : "";', '    }', '    private ControlDescriptions() {}', '}', '']
(root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/ui/ControlDescriptions.java').write_text('\n'.join(lines))
