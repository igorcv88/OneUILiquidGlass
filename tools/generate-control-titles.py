#!/usr/bin/env python3
"""Generate Android title resources from the presentation catalogue and translations."""
import hashlib
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
translations = json.loads((root / 'tools/control-title-translations.json').read_text())
source = (root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/config/Controls.java').read_text()
titles = set(re.findall(r'put\(c\("[^"]+",\s*"([^"]+)"\)', source))
titles.update(re.findall(r'\{"qs\.[^"]+",\s*"([^"]+\(descontinuado\))"\}', source))
missing = titles - translations.keys()
extra = translations.keys() - titles
if missing or extra:
    raise SystemExit(f'Update title translations: missing={sorted(missing)} extra={sorted(extra)}')
entries = [(title, translations[title], 'control_title_' + hashlib.sha1(title.encode()).hexdigest()[:12]) for title in sorted(titles)]
for folder, column in [('values', 1), ('values-pt-rBR', 0)]:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for entry in entries:
        value = escape(entry[column]).replace("'", "\\'")
        lines.append(f'    <string name="{entry[2]}">{value}</string>')
    lines.append('</resources>')
    (root / f'app/src/main/res/{folder}/control_titles.xml').write_text('\n'.join(lines) + '\n')
java = ['package io.github.igorcv88.oneuiliquidglass.ui;', '', 'import android.content.Context;', 'import io.github.igorcv88.oneuiliquidglass.R;', 'import io.github.igorcv88.oneuiliquidglass.config.Controls;', '', '/** Generated by tools/generate-control-titles.py; key and setting contracts remain unchanged. */', 'final class ControlTitles {', '    static int resource(Controls.Control control) {', '        switch (control.title) {']
for title, english, name in entries:
    java.append(f'            case {json.dumps(title, ensure_ascii=False)}: return R.string.{name};')
java += ['            default: return 0;', '        }', '    }', '    static String title(Context context, Controls.Control control) {', '        int id = resource(control);', '        return id == 0 ? control.title : context.getString(id);', '    }', '    private ControlTitles() {}', '}', '']
(root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/ui/ControlTitles.java').write_text('\n'.join(java))
