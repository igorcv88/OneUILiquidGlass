#!/usr/bin/env python3
"""Generate values/product_copy.xml (en) and values-pt-rBR/product_copy.xml from COPY_PT_EN.csv.

The CSV is the single source of the product copy. Output uses LF endings on every platform.
"""
import csv
import re
from pathlib import Path
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader(open(root / 'docs/OULG_UI_PLAN/COPY_PT_EN.csv', encoding='utf-8', newline='')))
ids = [r['id'] for r in rows]
if len(ids) != len(set(ids)):
    raise SystemExit('product copy: duplicate ids')
FORMAT_ARG = re.compile(r'%\d+\$[sd]')


def android(value):
    """Escape for an Android string resource: markup, apostrophes and a leading @ or ?."""
    text = escape(value).replace("'", "\\'").replace('"', '\\"')
    return '\\' + text if text[:1] in '@?' else text


def line(row, column):
    value = row[column]
    if not value:
        raise SystemExit(f'product copy: {row["id"]} has no {column} text')
    # A literal percent sign in a string without format arguments would be read as a format.
    plain = '' if FORMAT_ARG.search(value) else ' formatted="false"'
    return f'    <string name="{row["id"]}"{plain}>{android(value)}</string>'


for folder, column in (('values', 'en'), ('values-pt-rBR', 'pt_BR')):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by tools/generate-product-copy.py from docs/OULG_UI_PLAN/COPY_PT_EN.csv. Do not edit. -->',
             '<resources>']
    lines += [line(r, column) for r in rows]
    lines.append('</resources>')
    # formatted="false" only where a '%' appears without an argument.
    lines = [l.replace(' formatted="false"', '') if '%' not in l else l for l in lines]
    (root / f'app/src/main/res/{folder}/product_copy.xml').write_bytes(('\n'.join(lines) + '\n').encode('utf-8'))
