#!/usr/bin/env python3
"""Generate Android resources for catalogue choice and sentinel labels."""
import hashlib
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'tools/control-option-translations.json').read_text())
source = (root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/config/Controls.java').read_text()
options = set(re.findall(r'\.(?:auto|off)\("([^\"]*)"\)', source))
for label, description in re.findall(r'\.choice\("[^\"]*",\s*"([^\"]*)",\s*"([^\"]*)"\)', source):
    options.update((label, description))
if set(data) != options:
    raise SystemExit(f'Update option translations: missing={sorted(options - set(data))} extra={sorted(set(data) - options)}')
entries = [(key, data[key], 'control_option_' + hashlib.sha1(key.encode()).hexdigest()[:12]) for key in sorted(options) if key]
for folder, col in [('values', 1), ('values-pt-rBR', 0)]:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for e in entries:
        lines.append(f'    <string name="{e[2]}">{escape(e[col]).replace(chr(39), chr(92) + chr(39))}</string>')
    lines.append('</resources>')
    (root / f'app/src/main/res/{folder}/control_options.xml').write_text('\n'.join(lines) + '\n')
lines = ['package io.github.igorcv88.oneuiliquidglass.ui;', '', 'import android.content.Context;', 'import io.github.igorcv88.oneuiliquidglass.R;', '', '/** Generated by tools/generate-control-options.py. */', 'final class ControlOptions {', '    static int resource(String value) {', '        if (value == null || value.isEmpty()) return 0;', '        switch (value) {']
for pt, en, name in entries:
    lines.append(f'            case {json.dumps(pt, ensure_ascii=False)}: return R.string.{name};')
lines += ['            default: return 0;', '        }', '    }', '    static String text(Context context, String value) {', '        int id = resource(value);', '        return id == 0 ? value : context.getString(id);', '    }', '    private ControlOptions() {}', '}', '']
(root / 'app/src/main/java/io/github/igorcv88/oneuiliquidglass/ui/ControlOptions.java').write_text('\n'.join(lines))
